"""Choose the fixed set of synthetic calls for Phase 1 manual tagging.

Balanced on planted labels so the test covers every outcome, every scenario and failures of every
checklist item, plus some calls where the agent passed everything. The chosen call IDs are written to
configs/phase1_synthetic_calls.txt (tracked in git) so every rater tags the same calls.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from ..schema import REPO_ROOT
from .targets import TRANSCRIPT_ITEMS, load_synthetic

SELECTION_FILE = REPO_ROOT / "configs" / "phase1_synthetic_calls.txt"

# Outcome quotas for 50 calls: rare outcomes nearly in full, the rest spread over common ones.
DEFAULT_QUOTAS = {"transferred": 3, "hung_up": 4, "insurance_followup": 4, "refused_or_disputed": 4,
                  "paid": 10, "non_committal": 9, "payment_plan": 8, "promise_to_pay": 8}


def select_balanced(run: Path, quotas: dict[str, int] = DEFAULT_QUOTAS, prefer: set[str] = frozenset(),
                    all_pass_target: int = 8) -> pd.DataFrame:
    """Greedy pick within each outcome quota, favouring scenarios and failed items not yet covered."""
    calls = load_synthetic(run)
    order_file = run / "llm_order.txt"
    if order_file.exists():  # deterministic tie-break: generation order
        rank = {c: i for i, c in enumerate(order_file.read_text().split())}
        calls = calls.assign(rank_=calls["contact_id"].map(rank).fillna(1e9)).sort_values("rank_")
    fails = calls[TRANSCRIPT_ITEMS].eq("No")
    calls = calls.assign(n_fail_=fails.sum(axis=1))

    chosen: list[str] = []
    scen_count: dict[str, int] = {}
    fail_count = {k: 0 for k in TRANSCRIPT_ITEMS}
    all_pass = 0
    n_scen = calls["scenario"].nunique()
    total = sum(quotas.values())

    for outcome, quota in quotas.items():
        pool = calls[calls["outcome"] == outcome]
        for _ in range(min(quota, len(pool))):
            best, best_score = None, None
            for r in pool[~pool["contact_id"].isin(chosen)].itertuples():
                failed = [k for k in TRANSCRIPT_ITEMS if getattr(r, k) == "No"]
                score = 2.0 / (1 + scen_count.get(r.scenario, 0) * n_scen / max(len(chosen), 1))
                score += sum(1.0 / (1 + fail_count[k]) for k in failed)
                if not failed and all_pass < all_pass_target * len(chosen) / total + 1:
                    score += 1.5
                if r.contact_id in prefer:
                    score += 0.5
                if best_score is None or score > best_score:
                    best, best_score = r, score
            if best is None:
                break
            chosen.append(best.contact_id)
            scen_count[best.scenario] = scen_count.get(best.scenario, 0) + 1
            for k in TRANSCRIPT_ITEMS:
                fail_count[k] += getattr(best, k) == "No"
            all_pass += best.n_fail_ == 0
    return calls.set_index("contact_id").loc[chosen].reset_index()


def write_selection(selected: pd.DataFrame, path: Path = SELECTION_FILE) -> None:
    header = ("# Phase 1 synthetic calls for manual tagging (contact IDs in data/synthetic/run_llm).\n"
              "# Balanced on planted outcome, scenario and failed checklist items. Generated by\n"
              "# `salud-qa select-synthetic`; edit only if the team agrees to change the test set.\n")
    path.write_text(header + "\n".join(selected["contact_id"]) + "\n")


def read_selection(path: Path = SELECTION_FILE) -> set[str] | None:
    if not path.exists():
        return None
    return {ln.strip() for ln in path.read_text().splitlines() if ln.strip() and not ln.startswith("#")}
