"""Render synthetic call transcripts from planted call truth.

Two modes:
- template: rule-based dialogue, fast and fully reproducible. Each QA item maps to visible
  behavior (or its absence). Good for pipeline testing; its phrasing is formulaic, so a
  bag-of-words model will find it easier than real calls. Do not report template-only accuracy
  as a final result.
- llm: a prompt per call (see llm.py) for a self-hosted model to write more natural dialogue.

Format mirrors the redacted sample calls: 'Speaker: text' turns, [REDACTED ...] tokens and
'****' masking. Call Statusing and Grammar are not visible in a transcript by design: they
are judged from the CRM disposition and the agent note.
"""

from __future__ import annotations

import numpy as np

HEADER = ("Editorial note: Synthetic call generated by the BIG synthetic data generator. "
          "Fictional dialogue; no real person, account or recording.")

FILLERS = ["um", "uh", "umm", "you know", "like", "OK so"]


class Builder:
    def __init__(self, rng: np.random.Generator, noise: float):
        self.rng, self.noise, self.lines = rng, noise, []

    def pick(self, options):
        return options[int(self.rng.integers(len(options)))]

    def say(self, speaker: str, text: str | list[str]) -> None:
        if isinstance(text, list):
            text = self.pick(text)
        self.lines.append(f"{speaker}: {self._noisy(text)}")

    def _noisy(self, text: str) -> str:
        if self.noise <= 0:
            return text
        words = text.split()
        out = []
        for wd in words:
            r = self.rng.random()
            if r < self.noise * 0.12:
                out.append(self.pick(FILLERS) + ",")
            if r > 1 - self.noise * 0.05 and len(wd) > 3 and not wd.startswith("["):
                out.append("*" * len(wd))      # masked span, like the redacted samples
                continue
            if 0.5 < r < 0.5 + self.noise * 0.03:
                continue                       # dropped word (ASR)
            out.append(wd)
        return " ".join(out) if out else text


def _money(x: float) -> str:
    return f"${x:,.2f}"


def render_template(call: dict, rng: np.random.Generator, noise: float = 0.15) -> str:
    b = Builder(rng, noise)
    inbound = str(call["direction"]).startswith("inbound")
    scen = call["scenario"]
    caller = {"patient": "Patient", "non_patient_guarantor": "Patient Representative",
              "insurance": "Insurance Representative"}[call["caller_type"]]
    ok = {k[3:]: bool(v) for k, v in call.items() if k.startswith("qa_")}
    sent = call["sentiment_label"]
    bal = _money(call["total_balance_discussed"] or 0.0)
    res = call["true_result"]
    A = "Agent"

    # 1. Opening / greeting
    if inbound:
        b.say("Automated System (inferred)", "Thank you for calling the patient billing office. "
              "Please be advised this call is being recorded for quality and training purposes.")
        if ok["greeting"]:
            b.say(A, ["Thank you for calling patient financial services, this is [REDACTED NAME]. How can I help you today?",
                      "Good morning, patient billing, my name is [REDACTED NAME]. How may I help you?"])
        else:
            b.say(A, ["Billing.", "Yeah, go ahead.", "Hello?"])
    else:
        if ok["greeting"]:
            b.say(A, ["Hi, this is [REDACTED NAME] calling from the patient billing office on behalf of [REDACTED PROVIDER]. "
                      "This call may be recorded. May I speak with [REDACTED NAME]?",
                      "Good afternoon, my name is [REDACTED NAME] with patient financial services for [REDACTED PROVIDER], "
                      "on a recorded line. Am I speaking with [REDACTED NAME]?"])
        else:
            b.say(A, ["Yeah, is this [REDACTED NAME]?", "Hi, calling about a bill. Who am I talking to?"])
        b.say(caller, ["Yes, speaking.", "This is them, yeah.", "Who's calling?"]
              if caller == "Patient" else ["I'm their [REDACTED RELATIONSHIP], I handle the bills.", "This is their spouse."])

    if call.get("language") == "spanish":
        b.say(caller, "¿Habla español?")
        b.say(A, "Sí, claro. Puedo ayudarle en español.")
        b.lines.append("[Remainder of call conducted in Spanish; shown in English translation]")

    # 2. Reason for the call (patient-stated on inbound)
    reasons = {
        "wants_to_pay": ["I got a statement and I want to take care of it.", "I'm calling to make a payment on my bill."],
        "billing_question": ["I got this bill and I don't understand what it's for.",
                             "I have a statement here and the amount looks different from last month."],
        "insurance_issue": ["My insurance should have covered this, I don't know why I'm getting a bill.",
                            "I think the claim went to the wrong insurance."],
        "hardship": ["I lost my job a couple months ago and I just can't pay this right now.",
                     "Honestly money is really tight, I'm on a fixed income and I can't afford this."],
        "dispute": ["I already paid this. I don't owe anything.", "This charge is wrong, I never had that service."],
        "third_party": ["I'm calling from the patient's insurance plan about an authorization on [REDACTED SERVICE DATE].",
                        "I'm with [REDACTED INSURANCE NAME], calling about a denied claim for a member."],
    }
    if inbound:
        b.say(caller, reasons[scen])
    else:
        b.say(A, "I'm calling about an open balance on your account with [REDACTED PROVIDER].")

    # 3. Verification (compliance) and data capture
    def verify():
        b.say(A, ["Before we go over anything, can I please verify the patient's full name and date of birth?",
                  "For privacy I need to verify a couple of things first. Can I get the patient's name and date of birth?"])
        b.say(caller, "It's [REDACTED NAME], [REDACTED DOB RESPONSE].")
        b.say(A, "Thank you, I have the account pulled up.")

    def disclose():
        if scen != "third_party":
            b.say(A, [f"OK so I'm showing a balance of {bal} for your visit on [REDACTED SERVICE DATE].",
                      f"Your current patient balance is {bal}."])

    if scen == "third_party":
        if ok["compliance"]:
            b.say(A, "I can take down the details, but I can't share account information until I confirm I'm speaking with an authorized party.")
        else:
            b.say(A, f"Sure, let me look. Yeah I'm showing they still owe {bal} on that.")
    elif ok["compliance"]:
        verify()
        disclose()
    else:
        disclose()
        b.say(A, "Oh and what's the date of birth on there?")
        b.say(caller, "[REDACTED DOB RESPONSE].")

    if not inbound and scen != "third_party":
        b.say(caller, reasons[scen])

    # 4. Understanding needs, correct info, culture
    neg = sent == "negative"
    if neg:
        b.say(caller, ["This is ridiculous, I keep getting these calls.", "I'm really frustrated with this whole thing.",
                       "Nobody ever calls me back about this."])
    if ok["culture"]:
        b.say(A, ["I completely understand, and I'm sorry for the frustration. Let's see what we can do.",
                  "I hear you, that sounds stressful. I'm going to help you with this."])
    else:
        b.say(A, ["Well, the bill is still due regardless.", "Ma'am, sir, I just need to know how you want to pay today.",
                  "Look, I don't make the rules, the balance is the balance."])

    if ok["understanding_needs"]:
        follow = {
            "hardship": "It sounds like you're going through a hard time. We have a financial assistance program, "
                        "and based on what you told me you may qualify. I can send you the application, and we can also set up a low monthly plan.",
            "insurance_issue": "So just to make sure I understand, you believe your insurance should have paid this. Let me check what the claim shows.",
            "dispute": "Let me make sure I understand. You believe this was already paid, or the service is incorrect. Let me look at the payment history.",
            "billing_question": "So you want to know what this charge is for. Let me walk you through it.",
            "wants_to_pay": "Great, I can help you with that today.",
            "third_party": "So you're calling to confirm the authorization status for the scheduled procedure, correct?",
        }[scen]
        b.say(A, follow)
    else:
        b.say(A, ["Can you pay the full amount today?", "OK. So how much can you put down right now?"])
        if scen == "hardship":
            b.say(caller, "I just told you, I can't afford it.")

    if ok["correct_info"]:
        info = {
            "insurance_issue": "I see the claim was processed and your plan applied this to your deductible, which is why it's patient responsibility. "
                               "If you think that's wrong, I can request an insurance review.",
            "dispute": "I see one payment on [REDACTED DATE], and this balance is for a separate visit. I can send you an itemized bill so you can see each charge.",
            "billing_question": "This is the remaining balance after insurance for your visit, it went to your coinsurance.",
        }.get(scen)
        if info:
            b.say(A, info)
    else:
        b.say(A, ["I think it's probably your insurance, I'm not really sure, you'd have to call them.",
                  "It's something with the deductible maybe. It should all be on the statement."])

    # 5. Outcome
    outcome_lines = {
        "paid_account_full": [(caller, "OK, I'd like to pay the full amount today with a card."),
                              (A, "Sure. I'll take that payment now, you'll get a confirmation number. [REDACTED TRANSACTION NUMBER].")],
        "paid_guarantor_full": [(caller, "Let's just pay all of it, everything on the account."),
                                (A, f"OK, that's {bal} for all accounts. Payment processed, here's your confirmation [REDACTED TRANSACTION NUMBER].")],
        "partial_payment": [(caller, "I can't do all of it, but I can pay part of it today."),
                            (A, "That's fine, any amount helps. I've applied that payment to the account.")],
        "promised_to_pay": [(caller, f"I get paid on {call.get('promise_date') or 'Friday'}, I can pay it then."),
                            (A, f"OK, I'll note that you plan to pay on {call.get('promise_date') or 'Friday'}.")],
        "paid_plan_full": [(caller, "Could I do monthly payments instead?"),
                           (A, "Absolutely. I can set up a monthly payment plan, and we'll take the first payment today.")],
        "non_committal": [(caller, ["I'll have to think about it.", "I don't know, I'll see what I can do."]),
                          (A, "OK, no problem.")],
        "contested_balance": [(caller, "I'm not paying anything until I see what these charges are."),
                              (A, "Understood, I'll note that you're disputing the balance.")],
        "would_not_pay": [(caller, ["I'm not paying this.", "I'm not going to pay that, take me off your list."]),
                          (A, "OK, I'll note that on the account.")],
        "pursued_insurance": [(caller, "OK so I should call my insurance about this?"),
                              (A, "Yes, and I'll also put in a request for the claim to be reviewed on our side.")],
        "na_transferred": [(caller, "Can you get me to someone who can look at the authorization?"),
                           (A, "Yes, I'll transfer you to the provider's office now.")],
    }
    if call["hung_up"]:
        b.say(caller, ["You know what, forget it.", "I don't have time for this."])
        b.lines.append("[Call disconnected by caller]")
        return "\n\n".join([HEADER, *b.lines]) + "\n"
    for spk, txt in outcome_lines.get(res, []):
        b.say(spk, txt)

    # 6. Data capture and resolution
    if scen != "third_party":
        if ok["capturing_data"]:
            b.say(A, "Is [REDACTED PHONE NUMBER] still the best number to reach you, and is your mailing address the same?")
            b.say(caller, ["Yes, that's right.", "Actually I have a new address, it's [REDACTED UPDATED ADDRESS]."])
            b.say(A, "Thank you, I've updated that.")
    if ok["first_contact_resolution"]:
        b.say(A, ["Is there anything else I can help you with today?", "Did that answer all of your questions?"])
        b.say(caller, ["No, that's it. Thank you." if sent != "negative" else "No. That's it.",
                       "That's everything, thanks."])
    else:
        b.say(A, ["I'll have someone look into it and call you back.", "You'll need to call back later about the rest.",
                  "Let me transfer you, hold on."])
        b.say(caller, ["OK.", "Again? Fine."] if sent == "negative" else ["OK, thank you."])

    # 7. Closing
    if ok["culture"]:
        b.say(A, ["Thank you for calling, have a great day.", "Thanks so much, take care."])
    else:
        b.say(A, ["OK bye.", "Alright."])
    return "\n\n".join([HEADER, *b.lines]) + "\n"
